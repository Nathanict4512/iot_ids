"""
train_model.py
Trains the CNN-LSTM intrusion detector and saves everything the app needs
into ./model (ids_model.keras, scaler.joblib, metrics.json).

Usage
  python train_model.py                       # synthetic IoT flow data
  python train_model.py --csv my_flows.csv    # your own labelled flows
Your CSV must use the columns in ids_core.REQUIRED_COLUMNS plus a `label`
column holding: Normal, DDoS, Port Scan, Botnet or Brute Force.
"""
import argparse
import json
import os
import time

os.environ.setdefault("TF_CPP_MIN_LOG_LEVEL", "2")

import joblib
import numpy as np
import pandas as pd
import tensorflow as tf
from sklearn.metrics import (classification_report, confusion_matrix,
                             roc_auc_score)
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from tensorflow import keras
from tensorflow.keras import layers

import ids_core as core

ap = argparse.ArgumentParser()
ap.add_argument("--samples", type=int, default=40000)
ap.add_argument("--epochs", type=int, default=25)
ap.add_argument("--csv", default=None)
ap.add_argument("--seed", type=int, default=42)
args = ap.parse_args()

np.random.seed(args.seed)
tf.random.set_seed(args.seed)
rng = np.random.default_rng(args.seed)

# 1. Data -----------------------------------------------------------------
if args.csv:
    raw = pd.read_csv(args.csv)
    raw, notes = core.validate_frame(raw)
    raw["true_label"] = raw["label"]
    data_note = f"User-supplied dataset: {os.path.basename(args.csv)}"
else:
    raw = core.generate_flows(args.samples, rng, balanced=True)
    data_note = ("Synthetic IoT flow data (generated by ids_core.generate_flows) "
                 "modelling normal traffic, DDoS, port scan, botnet and brute-force flows.")
y = raw["true_label"].map({c: i for i, c in enumerate(core.CLASSES)}).values
X_df = raw[core.REQUIRED_COLUMNS]
print("Class counts:", raw["true_label"].value_counts().to_dict())

# 2. Split, encode, normalise ----------------------------------------------
Xtr_df, Xtmp_df, ytr, ytmp = train_test_split(X_df, y, test_size=0.30, stratify=y, random_state=args.seed)
Xva_df, Xte_df, yva, yte = train_test_split(Xtmp_df, ytmp, test_size=0.50, stratify=ytmp, random_state=args.seed)
scaler = StandardScaler().fit(core.to_matrix(Xtr_df).values)
Xtr, Xva, Xte = (core.transform(d, scaler) for d in (Xtr_df, Xva_df, Xte_df))

# 3. Model -----------------------------------------------------------------
inp = keras.Input(shape=Xtr.shape[1:])
x = layers.Conv1D(32, 3, padding="same", activation="relu")(inp)
x = layers.BatchNormalization()(x)
x = layers.MaxPooling1D(2)(x)
x = layers.Conv1D(64, 3, padding="same", activation="relu")(x)
x = layers.MaxPooling1D(2)(x)
x = layers.LSTM(64)(x)
x = layers.Dropout(0.3)(x)
x = layers.Dense(32, activation="relu")(x)
out = layers.Dense(len(core.CLASSES), activation="softmax")(x)
model = keras.Model(inp, out, name="cnn_lstm_ids")
model.compile(optimizer=keras.optimizers.Adam(1e-3),
              loss="sparse_categorical_crossentropy", metrics=["accuracy"])
model.summary()

hist = model.fit(
    Xtr, ytr, validation_data=(Xva, yva), epochs=args.epochs, batch_size=128,
    callbacks=[keras.callbacks.EarlyStopping(patience=4, restore_best_weights=True)],
    verbose=2)

# 4. Evaluate on the unseen test set ---------------------------------------
probs = model.predict(Xte, verbose=0)
pred = probs.argmax(1)
rep = classification_report(yte, pred, target_names=core.CLASSES, output_dict=True, zero_division=0)
cm = confusion_matrix(yte, pred).tolist()
yb, pb = (yte != 0).astype(int), (pred != 0).astype(int)
brep = classification_report(yb, pb, target_names=["Normal", "Intrusion"], output_dict=True, zero_division=0)
binary = {
    "accuracy": brep["accuracy"],
    "precision": brep["Intrusion"]["precision"],
    "recall": brep["Intrusion"]["recall"],
    "f1": brep["Intrusion"]["f1-score"],
    "roc_auc": float(roc_auc_score(yb, 1 - probs[:, 0])),
    "false_positive_rate": float(((pb == 1) & (yb == 0)).sum() / max((yb == 0).sum(), 1)),
}

# 5. Response-speed benchmark (single flow and batch of 32) ----------------
bench = core.generate_flows(300, np.random.default_rng(1))
single = []
for i in range(200):
    t0 = time.perf_counter()
    model(core.transform(bench.iloc[[i]], scaler), training=False).numpy()
    single.append((time.perf_counter() - t0) * 1000)
single = single[10:]  # drop warm-up
t0 = time.perf_counter()
model(core.transform(bench.iloc[:32], scaler), training=False).numpy()
batch_per_flow = (time.perf_counter() - t0) * 1000 / 32

metrics = {
    "data_note": data_note,
    "n_train": int(len(ytr)), "n_val": int(len(yva)), "n_test": int(len(yte)),
    "classes": core.CLASSES,
    "multiclass": {"accuracy": rep["accuracy"], "macro_precision": rep["macro avg"]["precision"],
                   "macro_recall": rep["macro avg"]["recall"], "macro_f1": rep["macro avg"]["f1-score"],
                   "per_class": {c: rep[c] for c in core.CLASSES}},
    "binary": binary,
    "confusion_matrix": cm,
    "history": {k: [float(v) for v in vals] for k, vals in hist.history.items()},
    "latency_ms": {"single_mean": float(np.mean(single)), "single_p95": float(np.percentile(single, 95)),
                   "batch32_per_flow": float(batch_per_flow)},
    "tensorflow": tf.__version__,
}
os.makedirs(core.MODEL_DIR, exist_ok=True)
model.save(core.MODEL_DIR / "ids_model.keras")
joblib.dump(scaler, core.MODEL_DIR / "scaler.joblib")
with open(core.MODEL_DIR / "metrics.json", "w") as f:
    json.dump(metrics, f, indent=2)

print(f"\nTest accuracy (5-class): {rep['accuracy']:.4f}")
print("Binary:", {k: round(v, 4) for k, v in binary.items()})
print("Latency (ms):", metrics["latency_ms"])
